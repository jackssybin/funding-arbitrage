#!/bin/bash
# ==========================================
# 每日自动发送日报和任务计划书脚本
# 每天 8:00 自动执行
# ==========================================

set -e

# 项目根目录
PROJECT_DIR="/root/.openclaw/workspace/funding-arbitrage"
cd "$PROJECT_DIR"

# 获取昨天的日期（日报是前一天的）
YESTERDAY=$(date -d "yesterday" +"%Y-%m-%d")
TODAY=$(date +"%Y-%m-%d")
DAY_OF_WEEK=$(date +"%u")  # 1=周一, 7=周日

# 文件路径
DAILY_REPORT="data/daily_reports/${YESTERDAY}.md"
TASK_PLAN="daily_tasks/Day_${DAY_OF_WEEK}.md"

# 飞书webhook（需要用户配置）
WEBHOOK_URL="${FEISHU_WEBHOOK:-}"

echo "========================================"
echo "📅 每日自动发送任务执行"
echo "🕐 时间: $(date '+%Y-%m-%d %H:%M:%S')"
echo "📊 昨日日报: $DAILY_REPORT"
echo "📋 今日任务: $TASK_PLAN"
echo "========================================"

# --------------------------
# 1. 先生成当天的任务计划书
# --------------------------
echo ""
echo "📝 生成今日任务计划书..."

mkdir -p daily_tasks

# 根据测试天数动态生成任务内容
case $DAY_OF_WEEK in
    1)  # 周一 = Day 1（启动日）
        cat > "$TASK_PLAN" << 'EOF'
# 📅 Day 1 任务计划书 - 启动日

## 🎯 今日目标
✅ 程序成功启动运行，日报功能正常，所有组件初始化完成

## 📋 任务清单
- [ ] 09:00 - 查看昨日自动生成的日报，确认数据记录正常
- [ ] 10:00 - 检查程序运行状态，确认PID存在、日志正常输出
- [ ] 14:00 - 检查仪表盘 http://localhost:8080 可正常访问
- [ ] 18:00 - 查看当日日志，确认没有异常报错
- [ ] 22:00 - 记录今日观察到的所有问题和异常

## ⏰ 资金费结算时间提醒
- 16:00（今天下午）：第一次结算窗口
- 24:00（今天半夜）：第二次结算窗口
- 明天08:00：第三次结算窗口

## ✅ 验收标准
1. 程序连续运行超过24小时没有崩溃
2. 日报文件正确生成在 data/daily_reports/ 目录下
3. 仪表盘可以正常访问，数据显示正确
4. 日志没有ERROR级别的错误

## 📊 重点观察指标
- 📈 程序内存占用是否稳定
- 📈 API调用成功率是否100%
- 📈 费率数据是否正常更新
- 📈 余额数据是否正确记录

## ⚠️ 可能遇到的风险
- 风险1：服务器网络波动导致API调用失败
  - 预案：内置重试机制会自动重试，失败超过10次会告警
- 风险2：日报0点没有生成
  - 预案：手动触发日报生成，检查日志找原因

## 📝 今日复盘小结
[今晚填写]
EOF
        ;;

    2)  # 周二 = Day 2（观察期）
        cat > "$TASK_PLAN" << 'EOF'
# 📅 Day 2 任务计划书 - 观察期

## 🎯 今日目标
✅ 观察开平仓逻辑是否正确，验证风控规则生效

## 📋 任务清单
- [ ] 09:00 - 查看昨日日报，核对资金费结算是否正确
- [ ] 10:00 - 检查当前持仓，如果有持仓，核对浮盈浮亏计算
- [ ] 12:00 - 手动模拟一次异常场景，验证熔断是否生效
- [ ] 16:00 - 观察资金费结算是否正常记录
- [ ] 20:00 - 如有开仓，观察止损/止盈逻辑是否正确

## ⏰ 时间安排
- 上午：数据分析和核对
- 下午：观察资金费结算
- 晚上：验证风控逻辑

## ✅ 验收标准
1. 开仓条件判断准确（费率>0.15%才开）
2. 止损/止盈触发正确（到点就平，不拖泥带水）
3. 资金费结算金额计算正确
4. 日报数据与实际运行数据一致

## 📊 重点观察指标
- 📈 开仓判断准确率：100%
- 📈 平仓触发准确率：100%
- 📈 资金费计算误差：0
- 📈 日报数据准确率：100%

## ⚠️ 可能遇到的风险
- 风险1：费率计算错误导致资金费不对
  - 预案：手工计算对比，发现问题立刻修复
- 风险2：止损没有触发
  - 预案：立刻平仓，查日志找原因

## 📝 今日复盘小结
[今晚填写]
EOF
        ;;

    3)  # 周三 = Day 3（观察期第二天）
        cat > "$TASK_PLAN" << 'EOF'
# 📅 Day 3 任务计划书 - 观察期第二天

## 🎯 今日目标
✅ 连续3天稳定运行，策略逻辑验证完成

## 📋 任务清单
- [ ] 09:00 - 查看昨日日报，汇总3天收益数据
- [ ] 10:00 - 检查有没有触发过熔断，分析触发原因
- [ ] 14:00 - 核对所有开平仓记录，有没有误开误平
- [ ] 18:00 - 统计3天的胜率、盈亏比、最大回撤
- [ ] 22:00 - 写3天观察总结，列出需要优化的点

## ✅ 验收标准
1. 连续72小时稳定运行，没有崩溃重启
2. 所有开平仓都有合理原因
3. 最大回撤 < 5%（目标 < 10%）
4. 资金费收益 > 手续费成本

## 📊 重点观察指标
- 📈 累计收益率：目标 > 0.5%
- 📈 最大回撤：< 5%
- 📈 交易胜率：> 60%
- 📈 盈亏比：> 1.5

## 📝 今日复盘小结
[今晚填写]
EOF
        ;;

    4)  # 周四 = Day 4（优化期）
        cat > "$TASK_PLAN" << 'EOF'
# 📅 Day 4 任务计划书 - 优化期

## 🎯 今日目标
✅ 根据前3天数据，微调参数，进一步提高策略稳定性

## 📋 任务清单
- [ ] 09:00 - 分析前3天数据，找出亏损的共性原因
- [ ] 11:00 - 讨论并确定需要调整的参数
- [ ] 14:00 - 上线调整后的参数（小步调整，一次只改一个）
- [ ] 18:00 - 观察调整后的效果，记录数据
- [ ] 22:00 - 对比调整前后的数据差异

## ✅ 验收标准
1. 参数调整有数据支撑，不是拍脑袋
2. 调整后收益率有提升，或者最大回撤有下降
3. 每次只改一个参数，有对照组

## 📊 可调整的参数
- 开仓费率阈值：0.15% → 可上下微调 ±0.03%
- 止损比例：2% → 可上下微调 ±0.5%
- 止盈比例：3% → 可上下微调 ±0.5%
- 最大持仓数：3 → 可调整 2-4

## 📝 今日复盘小结
[今晚填写]
EOF
        ;;

    5)  # 周五 = Day 5（优化期第二天）
        cat > "$TASK_PLAN" << 'EOF'
# 📅 Day 5 任务计划书 - 优化期第二天

## 🎯 今日目标
✅ 优化后的参数稳定运行，收益表现有改善

## 📋 任务清单
- [ ] 09:00 - 查看昨日日报，对比参数调整前后数据
- [ ] 10:00 - 确认优化有效，还是需要回滚
- [ ] 14:00 - 如果还有优化空间，继续微调第二个参数
- [ ] 18:00 - 观察第二次调整的效果
- [ ] 22:00 - 记录所有参数调整和效果对比

## ✅ 验收标准
1. 参数优化后策略表现有量化提升
2. 没有引入新的bug或异常
3. 有完整的A/B测试对比数据

## 📊 重点观察指标
- 📈 优化前后收益率对比
- 📈 优化前后最大回撤对比
- 📈 优化前后胜率对比

## 📝 今日复盘小结
[今晚填写]
EOF
        ;;

    6)  # 周六 = Day 6（压力测试）
        cat > "$TASK_PLAN" << 'EOF'
# 📅 Day 6 任务计划书 - 压力测试日

## 🎯 今日目标
✅ 主动测试各种异常场景，验证策略鲁棒性

## 📋 任务清单
- [ ] 09:00 - 模拟网络中断10分钟，看恢复后是否正常
- [ ] 11:00 - 手动暂停再恢复交易，验证状态切换正确
- [ ] 14:00 - 手动一键平仓，验证平仓功能正常
- [ ] 16:00 - 模拟连续3次亏损，验证熔断机制
- [ ] 20:00 - 重启程序，验证持久化数据正确恢复

## ✅ 验收标准
1. 所有异常场景都有妥善处理，不会亏大钱
2. 程序重启后数据完全恢复，没有丢失状态
3. 熔断机制生效，不会在极端行情下连续亏钱

## ⚠️ 注意事项
- 压力测试在模拟盘做，不要在实盘搞
- 每个测试完成后要恢复正常状态
- 记录每个测试的输入和输出

## 📝 今日复盘小结
[今晚填写]
EOF
        ;;

    7)  # 周日 = Day 7（总结日）
        cat > "$TASK_PLAN" << 'EOF'
# 📅 Day 7 任务计划书 - 总结日

## 🎯 今日目标
✅ 7天测试完成，输出完整测试报告，决定是否上实盘

## 📋 任务清单
- [ ] 09:00 - 汇总7天所有日报数据，做统计分析
- [ ] 10:00 - 计算7天总收益率、最大回撤、胜率、盈亏比
- [ ] 12:00 - 分析所有亏损交易，找出原因和改进方案
- [ ] 14:00 - 写完整的7天测试报告
- [ ] 18:00 - 讨论并投票：是否可以上实盘？
- [ ] 22:00 - 如果决定上实盘，写实盘上线checklist

## ✅ 实盘上线标准（必须全部满足）
1. ✅ 7天累计收益率 > 1%（目标年化 > 50%）
2. ✅ 最大回撤 < 10%
3. ✅ 交易胜率 > 60%
4. ✅ 连续7天没有崩溃或异常
5. ✅ 所有风控机制都正常触发过
6. ✅ 资金费收益 > 手续费成本 × 1.5倍

## 📊 最终统计指标
- 7天总收益率：_____%
- 最大回撤：_____%
- 交易次数：_____次
- 胜率：_____%
- 总资金费收益：_____ USDT
- 总手续费成本：_____ USDT
- 净收益：_____ USDT

## 📝 7天测试总结
[填写总结]

## 🎯 是否上实盘？  □ 是   □ 再跑一周模拟盘
EOF
        ;;
esac

echo "✅ 今日任务计划书已生成: $TASK_PLAN"

# --------------------------
# 2. 准备发送内容
# --------------------------
echo ""
echo "📨 准备发送内容..."

# 标题
TITLE="📅 【$TODAY】每日早报"

# 读取日报内容
if [ -f "$DAILY_REPORT" ]; then
    REPORT_CONTENT=$(cat "$DAILY_REPORT" | head -100)
else
    REPORT_CONTENT="⚠️ 昨日日报尚未生成，请检查程序运行状态"
fi

# 读取任务计划
TASK_CONTENT=$(cat "$TASK_PLAN" | head -80)

# 组合消息
MESSAGE=$(cat << EOF
$TITLE

━━━━━━━━━━━━━━━━━━━━━━━━━━
📊 【昨日运行日报】
━━━━━━━━━━━━━━━━━━━━━━━━━━
$REPORT_CONTENT

━━━━━━━━━━━━━━━━━━━━━━━━━━
📋 【今日任务计划】
━━━━━━━━━━━━━━━━━━━━━━━━━━
$TASK_CONTENT

━━━━━━━━━━━━━━━━━━━━━━━━━━
💡 提示
- 完整日报文件: $DAILY_REPORT
- 完整任务文件: $TASK_PLAN
- 仪表盘地址: http://localhost:8080
EOF
)

# --------------------------
# 3. 发送方式
# --------------------------

# 方式1：如果配置了飞书webhook，发送到飞书
if [ -n "$WEBHOOK_URL" ]; then
    echo ""
    echo "🚀 发送到飞书..."
    
    # 转义JSON特殊字符
    ESCAPED_MESSAGE=$(echo "$MESSAGE" | sed 's/"/\\"/g' | sed ':a;N;$!ba;s/\n/\\n/g')
    
    curl -s -X POST "$WEBHOOK_URL" \
        -H "Content-Type: application/json" \
        -d "{\"msg_type\":\"text\",\"content\":{\"text\":\"$ESCAPED_MESSAGE\"}}"
    
    echo "✅ 已发送到飞书"
else
    # 方式2：没有配置webhook，只打印到控制台
    echo ""
    echo "⚠️  未配置飞书Webhook，消息内容如下："
    echo "========================================"
    echo "$MESSAGE"
    echo "========================================"
    echo ""
    echo "💡 配置方法："
    echo "   1. 在飞书群里添加自定义机器人，获取webhook地址"
    echo "   2. 在.env文件中添加：FEISHU_WEBHOOK=你的地址"
    echo "   3. 重启定时任务即可自动发送"
fi

# --------------------------
# 4. 同时也保存一份合并的发送记录
# --------------------------
mkdir -p data/daily_send_logs
echo "$MESSAGE" > "data/daily_send_logs/${TODAY}.log"

echo ""
echo "✅ 每日任务执行完成！"
echo "📝 发送日志已保存: data/daily_send_logs/${TODAY}.log"
echo ""
